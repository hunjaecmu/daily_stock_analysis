function getPreferredHelpMap(locale?: string | null): SettingsHelpMap {
  const normalized = locale?.toLowerCase();
  if (normalized?.startsWith('en')) {
    return settingsHelpEnUS;
  }
  if (normalized?.startsWith('ko')) {
    return settingsHelpKoKR;
  }
  return settingsHelpZhCN;
}

function getFallbackHelpTitle(locale?: string | null): string {
  const normalized = locale?.toLowerCase();
  if (normalized?.startsWith('en')) {
    return 'Configuration help';
  }
  if (normalized?.startsWith('ko')) {
    return '설정 도움말';
  }
  return '配置说明';
}

export function getSettingsHelpContent(
  helpKey?: string | null,
  fallbackDescription?: string,
  locale?: string | null,
): SettingsHelpContent | null {
  if (!helpKey) {
    return null;
  }

  // 한국어 도움말이 없는 항목은 중국어보다 영어로 먼저 대체한다.
  const isKorean = locale?.toLowerCase().startsWith('ko');
  const localized = getPreferredHelpMap(locale)[helpKey]
    ?? (isKorean ? settingsHelpEnUS[helpKey] : undefined)
    ?? settingsHelpZhCN[helpKey];
  if (localized) {
    return localized;
  }

  if (fallbackDescription) {
    return {
      title: getFallbackHelpTitle(locale),
      summary: fallbackDescription,
    };
  }

  return null;
}
